-- Run this entire script once in Supabase Dashboard -> SQL Editor.
-- Event approval chains are configured by Intended User + Request Type.

create table if not exists public.event_request_types (
    id bigint generated by default as identity primary key,
    name varchar(255) not null unique,
    requires_department boolean not null default false,
    approval_roles jsonb,
    is_active boolean not null default true,
    created_at timestamp(0) without time zone,
    updated_at timestamp(0) without time zone
);

create table if not exists public.event_intended_users (
    id bigint generated by default as identity primary key,
    name varchar(255) not null unique,
    code varchar(255) not null unique,
    approval_roles jsonb,
    is_active boolean not null default true,
    created_at timestamp(0) without time zone,
    updated_at timestamp(0) without time zone
);

create table if not exists public.event_departments (
    id bigint generated by default as identity primary key,
    name varchar(255) not null unique,
    is_active boolean not null default true,
    created_at timestamp(0) without time zone,
    updated_at timestamp(0) without time zone
);

alter table public.event_requests add column if not exists approval_route jsonb;
alter table public.event_requests add column if not exists intended_user varchar(100);
alter table public.event_intended_users add column if not exists approval_roles jsonb;

